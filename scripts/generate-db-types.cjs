// Generate from the migration-derived local schema. Production drift still needs
// `supabase gen types` against the deployed project during release verification.
const fs = require("node:fs");
const { createTestDb } = require("../tests/helpers/local-db.cjs");
async function main() {
  const db = await createTestDb();
  try {
    const enums = (
      await db.query(
        `select t.typname,array_agg(e.enumlabel order by e.enumsortorder) labels from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' group by t.typname`,
      )
    ).rows;
    const enumNames = new Set(enums.map((row) => row.typname));
    const map = (type) =>
      enumNames.has(type)
        ? `Database['public']['Enums'][${JSON.stringify(type)}]`
        : type.startsWith("_")
          ? `(${map(type.slice(1))})[]`
          : [
                "int2",
                "int4",
                "int8",
                "integer",
                "bigint",
                "smallint",
                "numeric",
                "float4",
                "float8",
              ].includes(type)
            ? "number"
            : ["bool", "boolean"].includes(type)
              ? "boolean"
              : ["json", "jsonb"].includes(type)
                ? "Json"
                : type === "void"
                  ? "undefined"
                  : "string";
    const columns = (
      await db.query(
        `select table_name,column_name,udt_name,is_nullable,column_default,is_identity from information_schema.columns where table_schema='public' order by table_name,ordinal_position`,
      )
    ).rows;
    const fks = (
      await db.query(
        `select cl.relname as tab,c.conname as name,rl.relname as referenced,array(select a.attname from unnest(c.conkey) with ordinality k(attnum,ord) join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.attnum order by k.ord) as columns,array(select a.attname from unnest(c.confkey) with ordinality k(attnum,ord) join pg_attribute a on a.attrelid=c.confrelid and a.attnum=k.attnum order by k.ord) as referenced_columns from pg_constraint c join pg_class cl on cl.oid=c.conrelid join pg_namespace n on n.oid=cl.relnamespace join pg_class rl on rl.oid=c.confrelid where c.contype='f' and n.nspname='public'`,
      )
    ).rows;
    const functions = (
      await db.query(
        `select p.proname,p.proargnames,p.pronargdefaults,p.prorettype::regtype::text as returns,array(select t.typname from unnest(p.proargtypes) with ordinality a(oid,ord) join pg_type t on t.oid=a.oid order by a.ord) as args from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prorettype<>'trigger'::regtype order by p.proname`,
      )
    ).rows;
    let out = `// Generated by npm run db:types from migrations. Do not edit manually.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n`;
    for (const table of [...new Set(columns.map((row) => row.table_name))]) {
      const cols = columns.filter((row) => row.table_name === table);
      out += `${JSON.stringify(table)}: {\n`;
      for (const kind of ["Row", "Insert", "Update"])
        out += `${kind}: {\n${cols.map((c) => `${JSON.stringify(c.column_name)}${kind === "Update" || (kind === "Insert" && (c.is_nullable === "YES" || c.column_default || c.is_identity === "YES")) ? "?" : ""}: ${map(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n")}\n};\n`;
      out += `Relationships: [${fks
        .filter((row) => row.tab === table)
        .map(
          (row) =>
            `{foreignKeyName:${JSON.stringify(row.name)};columns:${JSON.stringify(row.columns)};isOneToOne:false;referencedRelation:${JSON.stringify(row.referenced)};referencedColumns:${JSON.stringify(row.referenced_columns)}}`,
        )
        .join(",")}];\n};\n`;
    }
    out += "}; Views: { [_ in never]: never }; Functions: {\n";
    for (const f of functions) {
      out += `${JSON.stringify(f.proname)}: {Args: {${f.args.map((type, i) => `${JSON.stringify(f.proargnames?.[i] || `arg${i}`)}${i >= f.args.length - f.pronargdefaults ? "?" : ""}: ${map(type)} | null`).join(";")}}; Returns: ${map(f.returns)}};\n`;
    }
    out +=
      "}; Enums: {\n" +
      enums
        .map(
          (row) =>
            `${JSON.stringify(row.typname)}: ${row.labels.map(JSON.stringify).join(" | ")};`,
        )
        .join("\n") +
      "\n}; CompositeTypes: { [_ in never]: never } } };\n";
    fs.writeFileSync("src/types/database.generated.ts", out);
    console.log("Generated Database types from all local migrations.");
  } finally {
    await db.close();
  }
}
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
